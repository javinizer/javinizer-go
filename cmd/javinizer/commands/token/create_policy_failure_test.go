package token

import (
	"context"
	"testing"

	"github.com/javinizer/javinizer-go/internal/config"
	"github.com/javinizer/javinizer-go/internal/database"
	"github.com/javinizer/javinizer-go/internal/models"
	"github.com/mattn/go-sqlite3"
	"github.com/stretchr/testify/require"
)

func TestTokenCreationPolicyPreservesExistingTokens(t *testing.T) {
	path := setupMiss4DB(t)
	cfg, err := config.Load(path)
	require.NoError(t, err)
	t.Setenv("JAVINIZER_DB", cfg.Database.DSN)
	db, err := database.New(&database.Config{Type: cfg.Database.Type, DSN: cfg.Database.DSN, LogLevel: "silent"})
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, db.Close()) })
	repo := database.NewApiTokenRepository(db)
	ctx := context.Background()
	require.NoError(t, repo.Create(ctx, &models.ApiToken{ID: "kept", Name: "existing fixture", TokenHash: "1111111111111111111111111111111111111111111111111111111111111111", TokenPrefix: "11111111"}))
	before, err := repo.FindByID(ctx, "kept")
	require.NoError(t, err)
	require.NoError(t, db.Exec(`CREATE TRIGGER reject_named_token BEFORE INSERT ON api_tokens WHEN NEW.name = 'rejected fixture' BEGIN SELECT RAISE(ABORT, 'token creation policy'); END`).Error)
	cmd := newCreateCommand()
	require.NoError(t, cmd.Flags().Set("name", "rejected fixture"))
	result, err := RunCreate(cmd, nil, path)
	require.Nil(t, result)
	require.Error(t, err)
	// UUIDs are generated by the real service; assert the complete stable error
	// format and the precise underlying SQLite constraint, not a fixed random ID.
	require.Regexp(t, `^failed to create token: create api token [0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}: token creation policy$`, err.Error())
	var sqliteErr sqlite3.Error
	require.ErrorAs(t, err, &sqliteErr)
	require.Equal(t, sqlite3.ErrConstraintTrigger, sqliteErr.ExtendedCode)
	active, err := repo.ListActive(ctx)
	require.NoError(t, err)
	require.Equal(t, []models.ApiToken{*before}, active)
}
