// These faults occur at the real filesystem boundary, after Undo admission.
// All other filesystem operations run against a private in-memory filesystem.
type permissionContractFS struct {
	afero.Fs
	renameFailure string
	removeFailure string
	renames       [][2]string
	removals      []string
	trace         []string
}

func (f *permissionContractFS) Rename(oldname, newname string) error {
	f.renames = append(f.renames, [2]string{oldname, newname})
	if filepath.Clean(oldname) == f.renameFailure {
		return &os.LinkError{Op: "rename", Old: oldname, New: newname, Err: os.ErrPermission}
	}
	return f.Fs.Rename(oldname, newname)
}

func (f *permissionContractFS) Remove(path string) error {
	f.removals = append(f.removals, filepath.Clean(path))
	f.trace = append(f.trace, "remove "+filepath.Clean(path))
	if filepath.Clean(path) == f.removeFailure {
		return &os.PathError{Op: "remove", Path: path, Err: os.ErrPermission}
	}
	return f.Fs.Remove(path)
}

func (f *permissionContractFS) Open(path string) (afero.File, error) {
	f.trace = append(f.trace, "open "+filepath.Clean(path))
	return f.Fs.Open(path)
}

type permissionContractStore struct {
	db   *database.DB
	path string
	repo *database.BatchFileOperationRepository
}

func newPermissionContractStore(t *testing.T) *permissionContractStore {
	t.Helper()
	s := &permissionContractStore{path: filepath.Join(t.TempDir(), "history.sqlite")}
	s.open(t)
	t.Cleanup(func() { require.NoError(t, s.db.Close()) })
	require.NoError(t, s.db.AutoMigrate(&models.BatchFileOperation{}, &models.Job{}))
	return s
}

func (s *permissionContractStore) open(t *testing.T) {
	t.Helper()
	var err error
	s.db, err = database.New(&database.Config{Type: "sqlite", DSN: s.path, LogLevel: "silent"})
	require.NoError(t, err)
	s.repo = database.NewBatchFileOperationRepository(s.db)
}

func (s *permissionContractStore) reopenRow(t *testing.T, id uint) *models.BatchFileOperation {
	t.Helper()
	require.NoError(t, s.db.Close())
	s.open(t)
	row, err := s.repo.FindByID(context.Background(), id)
	require.NoError(t, err)
	return row
}

func TestRevertBatchPermissionFailurePreservesLastValidLocation(t *testing.T) {
	for _, stage := range []string{"directory rename", "file within renamed directory", "ordinary move"} {
		t.Run(stage, func(t *testing.T) {
			ctx := context.Background()
			base := afero.NewMemMapFs()
			store := newPermissionContractStore(t)
			root := string(filepath.Separator)
			currentDir := filepath.Join(root, "library", "organized")
			originalDir := filepath.Join(root, "library", "original")
			if stage == "ordinary move" {
				originalDir = filepath.Join(root, "incoming", "original")
			}

			op := &models.BatchFileOperation{
				BatchJobID:     "permission-contract",
				MovieID:        "SYNTH-001",
				OriginalPath:   filepath.Join(originalDir, "original.mkv"),
				NewPath:        filepath.Join(currentDir, "organized.mkv"),
				OperationType:  models.OperationTypeMove,
				InPlaceRenamed: stage != "ordinary move",
				RevertStatus:   models.RevertStatusApplied,
			}
			if op.InPlaceRenamed {
				op.OriginalDirPath = originalDir
			}
			generatedPath := filepath.Join(currentDir, "generated.nfo")
			op.GeneratedFiles = models.MarshalLedgerJSON(models.GeneratedFilesJSON{Delete: []string{generatedPath}})
			createTestFile(t, base, op.NewPath, "synthetic primary bytes")
			createTestFile(t, base, generatedPath, "synthetic generated bytes")
			unrelated := filepath.Join(root, "unrelated", "keep.txt")
			createTestFile(t, base, unrelated, "unrelated bytes")
			require.NoError(t, base.MkdirAll(filepath.Dir(originalDir), 0o755))
			require.NoError(t, store.repo.Create(ctx, op))

			lastPrimary := op.NewPath
			lastGenerated := generatedPath
			fault := currentDir
			wantRenames := [][2]string{{currentDir, originalDir}}
			wantError := "failed to rename directory back"
			switch stage {
			case "file within renamed directory":
				lastPrimary = filepath.Join(originalDir, filepath.Base(op.NewPath))
				lastGenerated = filepath.Join(originalDir, filepath.Base(generatedPath))
				fault = lastPrimary
				wantRenames = append(wantRenames, [2]string{lastPrimary, op.OriginalPath})
				wantError = "failed to rename file within directory"
			case "ordinary move":
				fault = op.NewPath
				wantRenames = [][2]string{{op.NewPath, op.OriginalPath}}
				wantError = "failed to revert move"
			}
			fs := &permissionContractFS{Fs: base, renameFailure: filepath.Clean(fault)}

			result, err := NewReverter(fs, store.repo).RevertBatch(ctx, op.BatchJobID)

			require.NoError(t, err)
			require.Equal(t, 1, result.Total)
			require.Equal(t, 1, result.Failed)
			require.Zero(t, result.Succeeded)
			require.Zero(t, result.Skipped)
			require.Len(t, result.Outcomes, 1)
			require.Equal(t, op.ID, result.Outcomes[0].OperationID)
			require.Equal(t, models.RevertOutcomeFailed, result.Outcomes[0].Outcome)
			require.Equal(t, models.RevertReasonAccessDenied, result.Outcomes[0].Reason)
			require.Contains(t, result.Outcomes[0].Error, wantError)
			require.Equal(t, wantRenames, fs.renames, "the intended rename boundary must fail, without compensating mutations")
			require.Empty(t, fs.removals, "failed primary Undo must not clean up generated files or ancestors")
			require.Equal(t, "synthetic primary bytes", string(mustRead2(t, base, lastPrimary)))
			require.Equal(t, "synthetic generated bytes", string(mustRead2(t, base, lastGenerated)))
			require.Equal(t, "unrelated bytes", string(mustRead2(t, base, unrelated)))
			_, err = base.Stat(op.OriginalPath)
			require.ErrorIs(t, err, os.ErrNotExist, "the requested restoration never completed")
			if stage == "file within renamed directory" {
				_, err = base.Stat(currentDir)
				require.ErrorIs(t, err, os.ErrNotExist, "the completed directory rename leaves bytes at the original directory")
			}

			// Reopen SQLite instead of relying on the row held by Reverter.
			row := store.reopenRow(t, op.ID)
			require.Equal(t, models.RevertStatusFailed, row.RevertStatus)
			require.Nil(t, row.RevertedAt)
			requireOnlyUndoAdmissionChanged(t, op.GeneratedFiles, row.GeneratedFiles)
		})
	}
}

func TestRevertBatchCleanupPermissionFailureStopsAncestorWalk(t *testing.T) {
	ctx := context.Background()
	base := afero.NewMemMapFs()
	store := newPermissionContractStore(t)
	root := string(filepath.Separator)
	collection := filepath.Join(root, "cleanup-contract", "library", "collection")
	title := filepath.Join(collection, "title")
	op := &models.BatchFileOperation{
		BatchJobID:    "cleanup-permission-contract",
		MovieID:       "SYNTH-002",
		OriginalPath:  filepath.Join(root, "incoming", "original.mkv"),
		NewPath:       filepath.Join(title, "organized.mkv"),
		OperationType: models.OperationTypeMove,
		RevertStatus:  models.RevertStatusApplied,
	}
	createTestFile(t, base, op.NewPath, "synthetic primary bytes")
	unrelated := filepath.Join(root, "unrelated", "keep.txt")
	createTestFile(t, base, unrelated, "unrelated bytes")
	require.NoError(t, store.repo.Create(ctx, op))
	fs := &permissionContractFS{Fs: base, removeFailure: filepath.Clean(collection)}

	result, err := NewReverter(fs, store.repo).RevertBatch(ctx, op.BatchJobID)

	require.NoError(t, err)
	require.Equal(t, 1, result.Total)
	require.Equal(t, 1, result.Succeeded, "empty-directory cleanup is best effort after primary restoration")
	require.Zero(t, result.Failed)
	require.Zero(t, result.Skipped)
	require.Len(t, result.Outcomes, 1)
	require.Equal(t, models.RevertOutcomeReverted, result.Outcomes[0].Outcome)
	require.Empty(t, result.Outcomes[0].Reason)
	require.Empty(t, result.Outcomes[0].Error)
	require.Equal(t, [][2]string{{op.NewPath, op.OriginalPath}}, fs.renames)
	require.Equal(t, []string{title, collection}, fs.removals, "remove the empty leaf, then stop at the failed parent")
	require.Equal(t, "remove "+collection, fs.trace[len(fs.trace)-1], "cleanup must not inspect ancestors after Remove fails")
	_, err = base.Stat(title)
	require.ErrorIs(t, err, os.ErrNotExist)
	for _, retained := range []string{collection, filepath.Dir(collection), filepath.Dir(filepath.Dir(collection))} {
		info, err := base.Stat(retained)
		require.NoError(t, err)
		require.True(t, info.IsDir())
	}
	require.Equal(t, "synthetic primary bytes", string(mustRead2(t, base, op.OriginalPath)))
	require.Equal(t, "unrelated bytes", string(mustRead2(t, base, unrelated)))
	row := store.reopenRow(t, op.ID)
	require.Equal(t, models.RevertStatusReverted, row.RevertStatus)
	require.NotNil(t, row.RevertedAt)
	requireOnlyUndoAdmissionChanged(t, op.GeneratedFiles, row.GeneratedFiles)
}
